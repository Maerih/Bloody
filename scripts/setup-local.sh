#!/usr/bin/env bash
# Bloody — local setup on a Linux host WITHOUT Docker (normally run for you by ./install.sh).
#
# Uses the host's PostgreSQL, creates the Bloody roles/databases (it never changes the postgres
# superuser's password), writes a repo-root .env reachable on this server's IP (random passwords
# and secrets on a new install; an existing .env keeps its values), installs dependencies,
# migrates and seeds demo data. Safe to re-run.
#
#   bash scripts/setup-local.sh            # auto-detects the server IP
#   BLOODY_IP=192.168.1.3 bash scripts/setup-local.sh
#   BLOODY_SEED=0 bash scripts/setup-local.sh   # no demo data
set -euo pipefail
cd "$(dirname "$0")/.."
. scripts/lib.sh

# Privileged commands run directly as root, otherwise through sudo.
if [ "$(id -u)" = 0 ]; then SUDO=""; else SUDO="sudo"; fi
as_postgres() { if [ "$(id -u)" = 0 ]; then runuser -u postgres -- "$@"; else sudo -u postgres "$@"; fi; }
rand() { head -c 64 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }
env_get() { if [ -f .env ]; then grep -E "^$1=" .env | tail -1 | cut -d= -f2- || true; fi; }

# Keep the passwords of an existing install; a new install gets random ones.
existing_owner_pw="$(env_get DATABASE_URL | sed -nE 's#^postgres(ql)?://bloody_owner:([^@]*)@.*#\2#p')"
OWNER_PW="${BLOODY_OWNER_DB_PASSWORD:-${existing_owner_pw:-$(rand 32)}}"
APP_PW="${BLOODY_APP_DB_PASSWORD:-$(env_get BLOODY_APP_DB_PASSWORD)}"
APP_PW="${APP_PW:-$(rand 32)}"
IP="${BLOODY_IP:-$(bloody_detect_ip)}"

node_major="$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)"
if [ "$node_major" -lt 22 ]; then
  echo "Node.js 22 or newer is required (found $(node -v 2>/dev/null || echo none)). Run ./install.sh to install it." >&2
  exit 1
fi
command -v pnpm >/dev/null || { echo "pnpm not found. Run ./install.sh (or: corepack enable)." >&2; exit 1; }
command -v psql >/dev/null || { echo "PostgreSQL not found. Run ./install.sh (or: sudo apt install -y postgresql)." >&2; exit 1; }

$SUDO systemctl enable --now postgresql >/dev/null 2>&1 || $SUDO service postgresql start >/dev/null 2>&1 || true
for _ in $(seq 1 30); do as_postgres psql -qAtc "SELECT 1" >/dev/null 2>&1 && break; sleep 1; done
as_postgres psql -qAtc "SELECT 1" >/dev/null || { echo "PostgreSQL is installed but not accepting connections." >&2; exit 1; }

echo "==> Creating Bloody database roles (bloody_owner, bloody_app) and databases"
as_postgres psql -v ON_ERROR_STOP=1 -q -v owner_pw="$OWNER_PW" -v app_pw="$APP_PW" <<'SQL'
SELECT format('CREATE ROLE bloody_owner LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD %L', :'owner_pw')
  WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bloody_owner') \gexec
SELECT format('CREATE ROLE bloody_app LOGIN NOSUPERUSER NOBYPASSRLS NOINHERIT PASSWORD %L', :'app_pw')
  WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bloody_app') \gexec
-- The migration/seed role must bypass RLS to bootstrap the first tenant (dev seed). Request
-- handling never uses it: the API runs as bloody_app, which is always subject to RLS.
ALTER ROLE bloody_owner PASSWORD :'owner_pw' BYPASSRLS;
ALTER ROLE bloody_app PASSWORD :'app_pw';
SELECT 'CREATE DATABASE bloody OWNER bloody_owner' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'bloody') \gexec
SELECT 'CREATE DATABASE bloody_test OWNER bloody_owner' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'bloody_test') \gexec
GRANT CONNECT, TEMPORARY ON DATABASE bloody, bloody_test TO bloody_app;
SQL
for db in bloody bloody_test; do
  as_postgres psql -v ON_ERROR_STOP=1 -q -d "$db" <<'SQL'
ALTER SCHEMA public OWNER TO bloody_owner;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO bloody_app;
SQL
done

if [ ! -f .env ]; then
  echo "==> Writing .env (UI at http://$IP:5173)"
  cat > .env <<ENV
# Local/demo settings, generated by scripts/setup-local.sh (git-ignored). Keep this file private.
NODE_ENV=development
# API listens on this machine only; the browser reaches it through the web server's /api proxy.
HOST=127.0.0.1
PORT=4000
DATABASE_URL=postgres://bloody_owner:${OWNER_PW}@localhost:5432/bloody
BLOODY_APP_DB_PASSWORD=${APP_PW}
PUBLIC_URL=http://${IP}:5173
CORS_ORIGINS=http://${IP}:5173,http://localhost:5173
# Plain HTTP demo: browsers drop Secure cookies on non-localhost http. Use true behind HTTPS.
COOKIE_SECURE=false
# Web UI: listen on every interface so http://${IP}:5173 works from other machines.
BLOODY_WEB_HOST=0.0.0.0
# Local AI models (Ollama on this server, e.g. http://localhost:11434) are allowed for the demo.
BLOODY_AI_ALLOW_PRIVATE_ENDPOINTS=true
# Per-install secrets (sessions and encrypted integration credentials). Keep them: changing
# ENCRYPTION_KEY makes stored integration credentials unreadable.
JWT_SECRET=$(rand 64)
ENCRYPTION_KEY=$(head -c 32 /dev/urandom | base64)
ENV
  chmod 600 .env
else
  echo "==> .env already exists — keeping it, adding any missing settings"
fi
# A LAN install follows the server's address (DHCP): the start script refreshes PUBLIC_URL.
# ./install.sh sets the mode explicitly (lan / public with a domain or fixed IP).
if [ -z "$(bloody_env_get BLOODY_ADDRESS_MODE)" ]; then
  if [ -n "${BLOODY_IP:-}" ]; then bloody_env_set BLOODY_ADDRESS_MODE fixed; else bloody_env_set BLOODY_ADDRESS_MODE auto; fi
fi
[ "$(bloody_env_get BLOODY_ADDRESS_MODE)" = auto ] && bloody_refresh_address && echo "==> Server address: $(bloody_env_get PUBLIC_URL)"
# Make sure an older/hand-made .env still has what the IP-reachable demo needs.
ensure_env() { grep -qE "^$1=" .env || { echo "$1=$2" >> .env; echo "    added $1"; }; }
ensure_env COOKIE_SECURE false
ensure_env BLOODY_WEB_HOST 0.0.0.0
ensure_env PUBLIC_URL "http://${IP}:5173"
ensure_env CORS_ORIGINS "http://${IP}:5173,http://localhost:5173"
ensure_env BLOODY_AI_ALLOW_PRIVATE_ENDPOINTS true
ensure_env BLOODY_APP_DB_PASSWORD "$APP_PW"

echo "==> Installing dependencies"
pnpm install --frozen-lockfile
echo "==> Migrating"
pnpm db:migrate
if [ "${BLOODY_SEED:-1}" = 1 ]; then
  echo "==> Seeding demo data"
  pnpm db:seed
fi

echo "==> Setup complete"
